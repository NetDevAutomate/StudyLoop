"""Readable saved-results viewer; no model calls or rescoring."""

import argparse
import html
import json
from pathlib import Path


def safe(value):
    return html.escape(str(value))


def build(directory, destination):
    frozen = json.loads((directory / "frozen.json").read_text())
    report = json.loads((directory / "results.json").read_text())
    parts = [
        "<!doctype html><html lang='en'><meta charset='utf-8'><title>Stage 11</title>",
        "<style>body{font:18px/1.65 system-ui;max-width:1100px;margin:40px auto;padding:20px;",
        "color:#173042;background:#fafcfd}h1,h2{line-height:1.25}pre{white-space:pre-wrap;",
        "overflow-wrap:anywhere;background:#eff4f7;padding:16px}summary{cursor:pointer;",
        "padding:12px 0;font-weight:600}table{border-collapse:collapse;width:100%;margin:20px 0}",
        "th,td{padding:12px;text-align:left;border-bottom:1px solid #cad8df;vertical-align:top}",
        ".note{border-left:4px solid #168083;padding-left:18px}.columns{display:grid;",
        "grid-template-columns:1fr 1fr;gap:24px}@media(max-width:750px){.columns{display:block}}",
        "a{color:#086676}</style><h1>From a checked field to a justified decision</h1>",
        "<p>Saved synthetic observations · no model calls or rescoring</p>",
        "<p class='note'>Two different questions: does the proposal match the source, and does ",
        "the source meet the decision requirements? A source can be complete even when its ",
        "extraction is incomplete. The policy outputs below are generated by code; model prose ",
        "is never released as validated text.</p>",
        "<h2>Observed comparison</h2><table><tr><th>Output path</th><th>Valid decisions</th>",
        "<th>Unsupported choices</th><th>False blocks</th></tr>",
    ]
    for name, values in report["summary"].items():
        parts.append(
            "<tr>"
            + "".join(
                "<td>" + safe(v) + "</td>"
                for v in (
                    name,
                    values["valid_decisions"],
                    values["unsupported_choice"],
                    values["false_block"],
                )
            )
            + "</tr>"
        )
    parts.extend(
        [
            "</table><p>12 case conditions, 11 distinct source/target pairs, two draft calls per ",
            "condition. The paired omission control repeats one source intentionally. These are ",
            "development counts, not estimated real-world error rates. Artifact kind is fixture ",
            "metadata, not authenticated provenance. "
            "Quote resolution does not establish entailment.</p>",
            "<h2>Explore the decisions</h2><p>Start with <strong>omitted_present</strong> and ",
            "<strong>outside_distraction</strong>, then compare <strong>report_only</strong> and ",
            "<strong>duplicate_revision</strong>. "
            "Expand a case to see the evidence and both paths.</p>",
        ]
    )
    for case in frozen["cases"]:
        cid = case["id"]
        rows = [r for r in report["rows"] if r["case"] == cid]
        first = rows[0]
        expected = frozen["labels"]["cases"][cid]["expected_choice"]
        parts.append(
            f"<details><summary>{safe(cid)} — {safe(case['description_key'])} "
            f"· expected {safe(expected)}</summary>"
            "<div class='columns'><div><h3>Original source</h3>"
            f"<p>Kind: {safe(case['source']['kind'])}</p>"
            f"<pre>{safe(case['source']['text'])}</pre></div>"
            f"<div><h3>Target</h3><pre>{safe(json.dumps(case['target'], indent=2))}</pre>"
            f"<p>Case origin: {safe(case['origin'])}</p></div></div>"
        )
        parts.append(
            "<table><tr><th>Field</th><th>Candidate value</th><th>Candidate check</th>"
            "<th>Value from explicit source derivation</th></tr>"
        )
        adapter = first["outputs"]["source_adapter"]
        values = {fact["field"]: fact["value"] for fact in adapter["facts"]}
        for field, proposed in frozen["proposals"][cid].items():
            check = adapter["candidate_checks"][field]
            parts.append(
                "<tr>"
                + "".join(
                    "<td>" + safe(v) + "</td>"
                    for v in (field, proposed["value"], check["reason"], values.get(field))
                )
                + "</tr>"
            )
        parts.append("</table><h3>Code-owned outputs</h3>")
        for mode, output in first["outputs"].items():
            decision = output["decision"]
            reasons = ", ".join(issue["code"] for issue in output["issues"]) or "No blocking issue"
            parts.append(
                f"<h4>{safe(mode)} → {safe(decision['recommendation'])}</h4>"
                f"<p>{safe(decision['explanation'])}</p>"
                f"<p><strong>Reasons:</strong> {safe(reasons)}</p>"
                f"<p><strong>Next check:</strong> {safe(decision['next_check'])}</p>"
                "<details><summary>Exact evidence locators and policy trace</summary><pre>"
                + safe(json.dumps(output, indent=2))
                + "</pre></details>"
            )
        parts.append("<h3>Actual advisory drafts</h3>")
        for row in rows:
            answer = row.get("answer", {})
            parts.append(
                f"<h4>Repeat {row['repeat']} → {safe(answer.get('recommendation', 'invalid'))}</h4>"
                f"<p>{safe(answer.get('explanation', row.get('error_type', '')))}</p>"
                "<p><strong>Next check:</strong> "
                f"{safe(answer.get('next_check', 'unavailable'))}</p>"
                f"<p>Strict JSON: {safe(row.get('strict_json'))}; "
                f"parser: {safe(row.get('parse_method'))}</p>"
                "<details><summary>Draft citations and original text</summary><pre>"
                + safe(json.dumps(answer.get("citations"), indent=2))
                + "</pre><pre>"
                + safe(row.get("text", "unavailable"))
                + "</pre></details>"
            )
        parts.append(
            "<details><summary>Pre-run labels and reviewer disagreement</summary><pre>"
            + safe(json.dumps(frozen["labels"]["cases"][cid], indent=2))
            + "</pre></details></details>"
        )
    parts.append("</html>\n")
    with destination.open("x") as stream:
        stream.write("".join(parts))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    build(args.input, args.output)
    print(args.output)
